BLANK = ["00000"] * 7
FIRST_CHAR = 0x20
LAST_CHAR = 0x5A


def glyph_bytes(art):
    """Convert 7 rows x 5 columns art into 5 column-major bytes (bit0 = top row)."""
    columns = []
    for col in range(5):
        value = 0
        for row in range(7):
            if art[row][col] == "1":
                value |= 1 << row
        columns.append(value)
    return columns


